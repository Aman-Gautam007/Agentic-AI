# Integer
integer_num = 42
print(f"Integer: {integer_num}, Type: {type(integer_num)}")

# Float
float_num = 3.14
print(f"Float: {float_num}, Type: {type(float_num)}")

# Complex
complex_num = 3 + 4j
print(f"Complex: {complex_num}, Type: {type(complex_num)}")

# Boolean (subtype of int)
bool_num = True
print(f"Boolean: {bool_num}, Type: {type(bool_num)}")

# Long integer (Python 3 handles automatically)
long_num = 999999999999999999999
print(f"Long Integer: {long_num}, Type: {type(long_num)}")

# Hexadecimal
hex_num = 0xFF
print(f"Hexadecimal: {hex_num}, Type: {type(hex_num)}")

# Octal
octal_num = 0o77
print(f"Octal: {octal_num}, Type: {type(octal_num)}")

# Binary
binary_num = 0b1010
print(f"Binary: {binary_num}, Type: {type(binary_num)}")

# Scientific notation
scientific_num = 1.5e-3
print(f"Scientific: {scientific_num}, Type: {type(scientific_num)}")